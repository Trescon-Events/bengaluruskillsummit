/**
 * Helper function to retrieve SEO config for a given route pathname
 */
export function getSEOForPath(pathname) {
  if (!pathname) return DEFAULT_SEO;
  // Normalize pathname: remove trailing slash, lowercase, remove subfolder prefix if present
  let clean = pathname.toLowerCase().replace(/^\/bengaluruskillsummit(?:\.com)?/i, '') || '/';
  clean = clean.replace(/\/+$/, '') || '/';
  
  if (SEO_CONFIG[clean]) {
    return SEO_CONFIG[clean];
  }
  
  // Try matching without leading slash
  if (!clean.startsWith('/') && SEO_CONFIG['/' + clean]) {
    return SEO_CONFIG['/' + clean];
  }
  
  return DEFAULT_SEO;
}
